/**
 * Renders docs/data-contracts/*.md from db/contracts/entities.json (GOV-03).
 * The JSON is the source of truth and is checked against the live schema by
 * packages/platform/test/db/contracts.db.test.ts. Run: `pnpm data-contracts`.
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { loadDataContracts } from "@peopleledger/platform";

const out = new URL("../docs/data-contracts/", import.meta.url);
mkdirSync(out, { recursive: true });
for (const f of readdirSync(out)) if (f.endsWith(".md")) rmSync(new URL(f, out));

const c = loadDataContracts();
const cell = (v: string | null) => (v ?? "—").replace(/\|/g, "\\|");
const header = "<!-- Generated by `pnpm data-contracts` from db/contracts/entities.json. Do not edit by hand. -->\n\n";

for (const e of c.entities) {
  const cols = Object.entries(e.columns)
    .map(([name, col]) => `| \`${name}\` | ${col.type} | ${col.nullable ? "yes" : "no"} | ${col.classification} | ${cell(col.api ? `\`${col.api}\`` : null)} | ${cell(col.description)} |`)
    .join("\n");
  const timeCols = Object.keys(e.columns).filter((k) => /^(effective_from|effective_to|recorded_at|created_at|occurred_at)$/.test(k));
  writeFileSync(
    new URL(`${e.table}.md`, out),
    `${header}# \`${e.table}\`

${e.description}

| Property | Value |
|---|---|
| Owner module | ${e.owner} |
| Kind | ${e.kind} |
| Tenant scope | ${e.tenantScoped ? "Tenant scoped: `tenant_id` + row-level security, composite keys/FKs" : "Not tenant scoped"} |
| Runtime access | ${e.runtimeAccess ? "Granted to runtime roles (see migration grants)" : "None: no runtime role grants"} |
| Effective / recorded time | ${timeCols.length ? timeCols.map((t) => `\`${t}\``).join(", ") : "—"} |
| Retention class | \`${e.retentionClass}\`: ${c.retentionClasses[e.retentionClass]} |
| API mapping | ${cell(e.apiResource)} |
| Write path | ${cell(e.writePath)} |
| Migration behaviour | ${cell(e.migration)} |

## Constraints

${e.constraints.map((x) => `- ${x}`).join("\n")}

## Fields

| Column | Type | Nullable | Classification | API field | Description |
|---|---|---|---|---|---|
${cols}
`,
  );
}

writeFileSync(
  new URL("README.md", out),
  `${header}# Data contracts

Entity and field contracts for the database layer (GOV-03). Source of truth:
[db/contracts/entities.json](../../db/contracts/entities.json), verified against the live schema by
\`packages/platform/test/db/contracts.db.test.ts\`. Field classification drives audit and log redaction today;
field-level access enforcement (RBAC-04) is later work.

## Classifications

| Class | Meaning |
|---|---|
${Object.entries(c.classifications).map(([k, v]) => `| \`${k}\` | ${v} |`).join("\n")}

## Retention classes

Periods are not decided yet (see docs/phase-0/open-questions.md). Nothing is deleted automatically.

| Class | Meaning |
|---|---|
${Object.entries(c.retentionClasses).map(([k, v]) => `| \`${k}\` | ${v} |`).join("\n")}

## Entities

| Table | Owner | Tenant scoped | Kind | Retention |
|---|---|---|---|---|
${c.entities.map((e) => `| [\`${e.table}\`](${e.table}.md) | ${e.owner} | ${e.tenantScoped ? "yes" : "no"} | ${e.kind} | \`${e.retentionClass}\` |`).join("\n")}
`,
);
console.log(`Wrote ${c.entities.length} entity contracts`);
