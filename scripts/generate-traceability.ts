/**
 * Regenerates docs/traceability/requirements-matrix.md from Appendix F of the
 * requirements baseline (GOV-01). Implementation status lives in
 * docs/traceability/status.json so it is edited in one place; anything not
 * listed there stays "Planned". Run: `pnpm traceability`.
 *
 * Evidence rule (Appendix E.3): a "Passed" row must cite at least one test
 * file, every cited file must exist, and each must name the requirement ID in
 * its text. The script fails otherwise, so a status cannot outrun its tests.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
// Normalize CRLF (Windows checkouts) so the row pattern below matches.
const spec = readFileSync(new URL("docs/requirements/PeopleLedger_Product_Requirements_v3.1_Final.md", root), "utf8").replace(/\r\n/g, "\n");
const STATUSES = ["Planned", "In progress", "Passed"];
const status: Record<string, { status: string; evidence: string; tests?: string[] }> = JSON.parse(
  readFileSync(new URL("docs/traceability/status.json", root), "utf8"),
);

const appendixF = spec.slice(spec.indexOf("## Appendix F"));
const rows = [...appendixF.matchAll(/^\| ([A-Z]+-\d+) \| (R[012][*#]?) \| ([^|]+) \| ([^|]+) \| (AT-[A-Z]+-\d+) \| [^|]+ \|$/gm)];
// Appendix F lists 361 unique requirement IDs (Section 17, Appendix E.1a).
const ids = rows.map((r) => r[1]);
if (new Set(ids).size !== ids.length) throw new Error("Duplicate requirement ids in Appendix F");
if (rows.length !== 361) throw new Error(`Expected 361 Appendix F rows, found ${rows.length}`);

const unknown = Object.keys(status).filter((id) => !rows.some((r) => r[1] === id));
if (unknown.length > 0) throw new Error(`status.json references unknown requirement ids: ${unknown.join(", ")}`);

const problems: string[] = [];
for (const [id, s] of Object.entries(status)) {
  if (!STATUSES.includes(s.status)) problems.push(`${id}: unknown status "${s.status}"`);
  if (s.status === "Passed" && !(s.tests && s.tests.length > 0)) problems.push(`${id}: Passed without test evidence`);
  for (const file of s.tests ?? []) {
    const url = new URL(file, root);
    if (!existsSync(url)) problems.push(`${id}: evidence file ${file} does not exist`);
    else if (!readFileSync(url, "utf8").includes(id)) problems.push(`${id}: evidence file ${file} does not mention ${id}`);
  }
}
if (problems.length > 0) throw new Error(`Traceability evidence problems:\n${problems.join("\n")}`);

const counts: Record<string, number> = {};
const body = rows.map(([, id, release, role, deps, test]) => {
  const s = status[id!] ?? { status: "Planned", evidence: "" };
  counts[s.status] = (counts[s.status] ?? 0) + 1;
  const tests = (s.tests ?? []).map((t) => `[${t.split("/").pop()}](../../${t})`).join("<br>");
  return `| ${id} | ${release} | ${role!.trim()} | ${deps!.trim()} | ${test} | ${s.status} | ${s.evidence} | ${tests} |`;
});
const releases = (r: string) => rows.filter((row) => row[2]!.startsWith(r)).length;

const out = `# Requirement traceability matrix

Generated by \`pnpm traceability\` from Appendix F of
[the requirements baseline](../requirements/PeopleLedger_Product_Requirements_v3.1_Final.md) and
[status.json](status.json). Do not edit by hand.

Release totals: R0 ${releases("R0")}, R1 ${releases("R1")}, R2 ${releases("R2")} (asterisk = split scope, see Appendix F.1).
Status totals: ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(", ")}.

"Passed" means automated tests cover the requirement's full text and the cited test
files name the requirement (enforced by the generator). "Planned" rows may still list
partial evidence: code and tests exist for part of the requirement and the gap is
stated. "In progress" marks partial work from the first vertical slice. Named owners,
tickets and estimates are assigned in Phase 0.

| Requirement | Release | Accountable role | Dependencies | Acceptance test | Status | Evidence | Tests |
|---|---|---|---|---|---|---|---|
${body.join("\n")}
`;
writeFileSync(new URL("docs/traceability/requirements-matrix.md", root), out);
console.log(`Wrote ${rows.length} rows: ${JSON.stringify(counts)}`);
